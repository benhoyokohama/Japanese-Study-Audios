import json
from cue_detector import detect_cues

def build_lesson_json(lesson_id, items_list):
    mp3_path = f"lessons/{lesson_id}.mp3"
    json_path = f"lessons/{lesson_id}.json"
    
    cues = detect_cues(mp3_path, threshold=0.85)
    print(f"[{lesson_id}] 检测到 {len(cues)} 个提示音节点，准备匹配 {len(items_list)} 个词条...")
    
    if len(cues) != len(items_list):
        print(f"⚠️ 警告: 提示音数量 ({len(cues)}) 与文本词条数量 ({len(items_list)}) 不一致，请核对 PDF 词条范围！")
    
    sentences = []
    current_start = 0.0
    for idx, (end_t, conf) in enumerate(cues):
        item = items_list[idx] if idx < len(items_list) else {"jp": f"未配对词条 {idx+1}", "cn": ""}
        sentences.append({
            "id": idx + 1,
            "start": current_start,
            "end": end_t,
            "jp": item["jp"],
            "cn": item.get("cn", "")
        })
        current_start = end_t

    with open(json_path, "w", encoding="utf-8") as f:
        json.dump(sentences, f, ensure_ascii=False, indent=2)
    print(f"✅ 成功生成 {json_path} (共 {len(sentences)} 条)")

